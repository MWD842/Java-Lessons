        Scanner sc = new Scanner(System.in);
        int R = sc.nextInt();
        int C = sc.nextInt();
        int[][] arr = new int[R][C];
        for (int i=0; i<R; i++){
            for (int j=0; j<C; j++){
                arr[i][j] = sc.nextInt();
            }
        }
        int X = sc.nextInt();
        boolean isFound = false;
        for(int j=0; j<C; j++){
            for(int i=0; i<R; i++){
                if (arr[i][j] == X){
                    System.out.println(i+" "+j);
                    isFound = true;
                    break;
                }
            }
            if (isFound){
                break;
            }
        }
